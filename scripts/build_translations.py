def _flatten(node, prefix=""):
    if isinstance(node, dict):
        for key, value in node.items():
            yield from _flatten(value, f"{prefix}{key}.")
    else:
        yield prefix[:-1]


def _text(table: dict[str, str], name: str) -> str:
    name, _, phase = name.partition("|")
    return table[name].replace("{P}", phase) if phase else table[name]


def build() -> None:
    english = json.loads((TRANSLATIONS / "en.json").read_text(encoding="utf-8"))
    flat = list(_flatten(english))
    unmapped = [key for key in flat if key not in KEYS]
    if unmapped:
        raise SystemExit(f"No table entry for English keys: {unmapped}")
    for language, table in LANGUAGES.items():
        result: dict = {}
        for key in flat:
            node = result
            *parents, leaf = key.split(".")
            for part in parents:
                node = node.setdefault(part, {})
            node[leaf] = _text(table, KEYS[key])
        (TRANSLATIONS / f"{language}.json").write_text(
            json.dumps(result, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8", newline="\n",
        )
        print(f"{language}: {len(flat)} strings")


if __name__ == "__main__":
    build()
